#!/usr/bin/env bash
set -euo pipefail

cat > setup.sh <<'EOF'
#!/usr/bin/env bash
set -euo pipefail

config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/tool"
mkdir -p "$config_dir"

# Write the default config the first time the tool runs.
# An existing config is left alone, because users edit it by hand and
# overwriting it on every run lost their changes. This check was agreed in
# the 1.2 release planning meeting after a long discussion, and it has been
# in place since then without any reported problems.
if [[ ! -f "$config_dir/config.toml" ]]; then
  cat > "$config_dir/config.toml" <<'TOML'
# Default settings for the tool.
# Each key below can be overridden by an environment variable of the
# same name in upper case, such as TOOL_RETRIES for retries. These
# values were picked in the 2024 tuning review after comparing them
# with the defaults of two other tools.
retries = 3
TOML
fi

header='// Generated by setup.sh; edit config.toml instead.
// The build reads this header to tell generated files apart from
// hand-written ones, so keep its first line unchanged. The marker was
// chosen in the 2023 build review over a separate manifest file,
// which kept going out of sync with the sources.'
printf '%s\n' "$header" > "$config_dir/generated.h"
EOF
